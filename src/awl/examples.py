def _answer(settings: dict, query: str) -> str:
    """Run *query* against this flavour's graph and return the rows as a table.

    Answered at build time rather than transcribed, so a query that stops
    working stops appearing on the page as though it still did.
    """
    graph = pipeline.to_graph(
        FLAVOUR_SOURCE,
        module="battery.procedure",
        file="procedure.py",
        index=_FLAVOUR_INDEX,
        layers=settings.get("layers"),
        spans=settings.get("spans"),
        trivia=settings.get("trivia"),
    )
    result = graph.query(query)
    names = [str(name) for name in result.vars or []]
    rows = [[_readable(value) for value in row] for row in result]
    if not rows:
        return "No rows. This flavour does not carry what the question asks for."
    header = "| " + " | ".join(names) + " |"
    rule = "| " + " | ".join("---" for _ in names) + " |"
    return "\n".join([header, rule, *("| " + " | ".join(row) + " |" for row in rows)])


def _with_prefixes(query: str) -> str:
    """Return *query* preceded by the prefixes it actually uses.

    Shown and run as one string, so what a reader copies is what produced the
    answer under it. Only the prefixes the query names are included: binding
    three every time would put two lines of noise above every question.
    """
    used = [line for line in _PREFIXES.splitlines() if f"{line.split()[1]}" in query]
    return "\n".join([*used, "", query.strip()]) if used else query.strip()


def _readable(value: Any) -> str:
    """Return a result cell, shortened to the part that identifies it."""
    if value is None:
        return ""
    text = str(value)
    if text.startswith("https://w3id.org/awl/py/"):
        return "`py:" + text[len("https://w3id.org/awl/py/") :] + "`"
    if text.startswith("https://w3id.org/awl/schema/"):
        return "`awl:" + text[len("https://w3id.org/awl/schema/") :] + "`"
    return text


def _flavour_view(title: str, note: str, settings: dict, question: str, query: str) -> str:
    """Return one flavour: the source, the two notations, then a question."""
    return "\n".join([
        f"## {title}",
        "",
        note,
        "",
        '<div class="grid" markdown>',
        "",
        '<div markdown="1">',
        "",
        _tabs([("Python", FLAVOUR_SOURCE.rstrip(), "python")]),
        "",
        "</div>",
        "",
        '<div markdown="1">',
        "",
        _tabs([
            ("AWL AST", _flavour_document(settings), "json"),
            ("RDF", _flavour_turtle(settings), "turtle"),
            ("Graph", _flavour_mermaid(settings), "mermaid"),
        ]),
        "",
        "</div>",
        "",
        "</div>",
        "",
        f"**{question}**",
        "",
        _fence(_with_prefixes(query), "sparql"),
        "",
        _answer(settings, _with_prefixes(query)),
        "",
    ])


