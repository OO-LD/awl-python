def _split_view(path: Path) -> str:
    """Return one file's source beside its representations."""
    return "\n".join([
        f"## `{path.parent.name}/{path.name}`",
        "",
        '<div class="grid" markdown>',
        "",
        '<div markdown="1">',
        "",
        _tabs([("Python", path.read_text(encoding="utf-8").rstrip(), "python")]),
        "",
        "</div>",
        "",
        '<div markdown="1">',
        "",
        _tabs([(title, body, "turtle" if title == "RDF" else "json") for title, body in _views(path)]),
        "",
        "</div>",
        "",
        "</div>",
        "",
    ])


def define_env(env) -> None:
    """Register the macros the documentation calls."""

    @env.macro
    def corpus_examples() -> str:
        """Return the split view for every file in the validation corpus."""
        files = sorted(
            contracts.corpus_files(),
            key=lambda path: (_ORDER.get(path.parent.name, 9), path.name),
        )
        return "\n".join(_split_view(path) for path in files)

    @env.macro
    def shared_context() -> str:
        """Return the context every flavour shares, inside a collapsed block."""
        return "\n".join([
            '??? note "The `@context` every flavour shares"',
            "",
            _fence(flavour_context(), "json", "    "),
        ])

    @env.macro
    def single_flavours() -> str:
        """Return one section per lookup, each on its own."""
        return "\n".join(_flavour_view(*flavour) for flavour in _SINGLE_FLAVOURS)

    @env.macro
    def combined_flavours() -> str:
        """Return the lookups combined, ending with what a query runs against."""
        return "\n".join(_flavour_view(*flavour) for flavour in _COMBINED_FLAVOURS)
